import {
  colors,
  fonts,
  MIN_TOUCH_TARGET,
  membership,
  motion,
  radius,
  shadows,
  sizes,
  type,
  type ColorTokens,
} from "./tokens";

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`).replace(/([a-z])(\d)/g, "$1-$2");

function vars(c: ColorTokens, indent = "  ") {
  return Object.entries(c)
    .map(([k, v]) => `${indent}--${kebab(k)}: ${v};`)
    .join("\n");
}

function lines(entries: [string, string | number][], indent = "  ") {
  return entries.map(([k, v]) => `${indent}--${k}: ${v};`).join("\n");
}

/** Theme-independent tokens: fonts, radius, type scale, sizes, motion, membership material. */
function staticTokens() {
  return [
    ["font-stack-sans", fonts.sans],
    ["font-stack-serif", fonts.serif],
    ["font-stack-mono", fonts.mono],
    ...Object.entries(radius).map(([k, v]) => [`radius-token-${kebab(k)}`, `${v}px`] as [string, string]),
    ...Object.entries(type).flatMap(([k, t]) => [
      [`type-${kebab(k)}-size`, `${t.size}px`] as [string, string],
      [`type-${kebab(k)}-line`, `${t.line}px`] as [string, string],
      [`type-${kebab(k)}-weight`, String(t.weight)] as [string, string],
      [`type-${kebab(k)}-tracking`, `${t.tracking}px`] as [string, string],
    ]),
    ...Object.entries(sizes).map(([k, v]) => [`size-${kebab(k)}`, `${v}px`] as [string, string]),
    ["touch-target", `${MIN_TOUCH_TARGET}px`],
    ["motion-fast", `${motion.fastMs}ms`],
    ["motion-base", `${motion.baseMs}ms`],
    ["motion-slow", `${motion.slowMs}ms`],
    ["motion-spring", motion.spring],
    ["motion-press-scale", String(motion.pressScale)],
    ["motion-press-opacity", String(motion.pressOpacity)],
    ["motion-bar-blur", `${motion.barBlurPx}px`],
    ...Object.entries(membership).map(([k, v]) => [`membership-${kebab(k)}`, v] as [string, string]),
    ["shadow-token-membership-card", shadows.membershipCard],
    ["shadow-token-thumb", shadows.thumb],
  ] as [string, string][];
}

/** Renders the theme CSS from tokens. Dark is the default; light applies explicitly or via the system setting. */
export function renderTokensCss(): string {
  return `/* GENERATED by \`npm run tokens\` from src/design/tokens.ts — do not edit by hand. */

:root,
[data-theme="dark"] {
  color-scheme: dark;
${vars(colors.dark)}
  --shadow-token-overlay: ${shadows.overlay.dark};
}

[data-theme="light"] {
  color-scheme: light;
${vars(colors.light)}
  --shadow-token-overlay: ${shadows.overlay.light};
}

@media (prefers-color-scheme: light) {
  [data-theme="system"] {
    color-scheme: light;
${vars(colors.light, "    ")}
    --shadow-token-overlay: ${shadows.overlay.light};
  }
}

@media (prefers-color-scheme: dark) {
  [data-theme="system"] {
    color-scheme: dark;
  }
}

:root {
${lines(staticTokens())}
}
`;
}
